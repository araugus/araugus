"""End-to-end experiment: diagnostics -> learners -> evaluation -> business simulation -> segments."""

from __future__ import annotations

import json
from dataclasses import asdict

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split

from . import plots
from .business import CampaignEconomics, bootstrap_profit_gain, optimal_fraction, profit_curve
from .data import ARMS, CONTROL, OUTCOMES, PROJECT_ROOT, binary_setup, load_raw, make_features
from .metrics import auuc, bootstrap_metric, qini_coefficient, qini_curve, uplift_at_k, uplift_by_bin
from .modeling import SEED, leaf_rules, make_learners, out_of_fold_uplift, stratum, surrogate_tree
from .stats import ate_table, ate_with_ci, balance_table, segment_effects

TREATMENT_ARM = "Womens E-Mail"
OUTCOME = "visit"
TEST_SIZE = 0.4
FIG_DIR = PROJECT_ROOT / "reports" / "figures"
ART_DIR = PROJECT_ROOT / "artifacts"
SENSITIVITY_COSTS = (0.05, 0.10, 0.15, 0.20)


def _md(df: pd.DataFrame, floatfmt: str = ".4f") -> str:
    df = df.copy()
    for col in df.columns:
        if pd.api.types.is_integer_dtype(df[col]):
            df[col] = df[col].astype(str)
    return df.to_markdown(index=False, floatfmt=floatfmt)


def run(n_boot: int = 200) -> dict:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    ART_DIR.mkdir(parents=True, exist_ok=True)
    report: list[str] = ["# Results (generated by `scripts/run_pipeline.py` - do not edit by hand)\n"]
    summary: dict = {}

    # 1. Experiment diagnostics on the full 3-arm data -------------------------------
    raw = load_raw()
    X_all = make_features(raw)
    bal = balance_table(X_all, raw["segment"], CONTROL)
    ate = ate_table(raw, list(ARMS), CONTROL, list(OUTCOMES))
    plots.plot_ate(ate, FIG_DIR / "ate_by_arm.png")
    max_smd = float(bal.filter(like="smd_").abs().to_numpy().max())
    summary["n_customers"] = len(raw)
    summary["arm_sizes"] = raw["segment"].value_counts().to_dict()
    summary["max_abs_smd"] = max_smd
    report += [
        "## Randomisation balance (SMD vs control; ANOVA p across 3 arms)\n",
        _md(bal),
        "",
        f"Max |SMD| = {max_smd:.4f}\n",
        "## Average treatment effects (Welch 95% CI)\n",
        _md(
            ate[
                [
                    "arm",
                    "outcome",
                    "mean_control",
                    "mean_treated",
                    "ate",
                    "ci_low",
                    "ci_high",
                    "relative_lift",
                    "p_value",
                ]
            ]
        ),
        "",
    ]

    # 2. Binary set-up: women's e-mail vs no e-mail, outcome = visit -------------------
    data = binary_setup(raw, TREATMENT_ARM, OUTCOME)
    idx_tr, idx_te = train_test_split(
        np.arange(len(data.y)), test_size=TEST_SIZE, random_state=SEED, stratify=stratum(data.treatment, data.y)
    )
    X_tr, X_te = data.X.iloc[idx_tr], data.X.iloc[idx_te]
    t_tr, t_te, y_tr, y_te = data.treatment[idx_tr], data.treatment[idx_te], data.y[idx_tr], data.y[idx_te]
    test_ate = ate_with_ci(y_te, t_te)["ate"]
    summary["setup"] = {
        "treatment": TREATMENT_ARM,
        "control": CONTROL,
        "outcome": OUTCOME,
        "n_train": len(idx_tr),
        "n_test": len(idx_te),
        "test_ate": test_ate,
    }

    # 3. Learners: CV on train (selection), refit on full train, score test once -------
    rows, oof, test_scores = [], {}, {}
    for name, factory in make_learners().items():
        oof[name] = out_of_fold_uplift(factory, X_tr, t_tr, y_tr)
        test_scores[name] = factory().fit(X_tr, t_tr, y_tr).predict_uplift(X_te)
    rng = np.random.default_rng(SEED)
    test_scores["Random targeting"] = rng.random(len(y_te))
    oof["Random targeting"] = rng.random(len(y_tr))
    for name, s in test_scores.items():
        lo, hi = bootstrap_metric(qini_coefficient, y_te, t_te, s, n_boot=n_boot, seed=SEED)
        rows.append(
            {
                "model": name,
                "cv_qini": qini_coefficient(y_tr, t_tr, oof[name]),
                "test_qini": qini_coefficient(y_te, t_te, s),
                "test_qini_ci_low": lo,
                "test_qini_ci_high": hi,
                "test_auuc": auuc(y_te, t_te, s),
                "uplift@10%": uplift_at_k(y_te, t_te, s, 0.1),
                "uplift@30%": uplift_at_k(y_te, t_te, s, 0.3),
            }
        )
    metrics_df = pd.DataFrame(rows)
    learners_only = metrics_df[metrics_df["model"] != "Random targeting"]
    best = str(learners_only.loc[learners_only["cv_qini"].idxmax(), "model"])
    summary["model_metrics"] = metrics_df.to_dict(orient="records")
    summary["best_model_by_cv"] = best
    report += [
        f"## Model comparison ({TREATMENT_ARM} vs {CONTROL}, outcome = {OUTCOME})\n",
        f"Train n = {len(idx_tr)}, test n = {len(idx_te)}; test-set ATE = {test_ate:.4f}. "
        f"Qini CI = {n_boot}-sample bootstrap on the test set. Best model by CV Qini: **{best}**.\n",
        _md(metrics_df),
        "",
    ]

    model_names = [n for n in test_scores if n != "Random targeting"]
    plots.plot_curves(
        {n: qini_curve(y_te, t_te, test_scores[n]) for n in model_names},
        "Qini curves on the held-out test set",
        "Incremental visits (Qini)",
        FIG_DIR / "qini_curves.png",
    )
    dec = uplift_by_bin(y_te, t_te, test_scores[best], 10)
    plots.plot_deciles(dec, test_ate, best, FIG_DIR / "uplift_by_decile.png")
    report += [f"## Uplift by decile - {best} (test set)\n", _md(dec), ""]

    # 4. Business simulation ------------------------------------------------------------
    econ = CampaignEconomics()
    spend_ratio = (
        ate.query("arm == @TREATMENT_ARM and outcome == 'spend'")["ate"].item()
        / ate.query("arm == @TREATMENT_ARM and outcome == 'visit'")["ate"].item()
    )
    profit_test = {n: profit_curve(y_te, t_te, test_scores[n], econ) for n in test_scores}
    # Targeting depth chosen on out-of-fold train predictions, never on the test set.
    k_star = float(optimal_fraction(profit_curve(y_tr, t_tr, oof[best], econ))["fraction"])
    curve = profit_test[best]
    at = lambda c, k: c.iloc[(c["fraction"] - k).abs().idxmin()]  # noqa: E731
    biz = pd.DataFrame(
        [
            {
                "strategy": "Contact no one",
                **at(curve, 0.0)[["fraction", "contacts", "incremental_responses", "campaign_cost", "profit", "roi"]],
            },
            {
                "strategy": "Contact everyone (blanket)",
                **at(curve, 1.0)[["fraction", "contacts", "incremental_responses", "campaign_cost", "profit", "roi"]],
            },
            {
                "strategy": f"{best}: top {k_star:.0%} (k chosen on CV)",
                **at(curve, k_star)[
                    ["fraction", "contacts", "incremental_responses", "campaign_cost", "profit", "roi"]
                ],
            },
            {
                "strategy": f"Random targeting: {k_star:.0%}",
                **at(profit_test["Random targeting"], k_star)[
                    ["fraction", "contacts", "incremental_responses", "campaign_cost", "profit", "roi"]
                ],
            },
            {
                "strategy": f"{best}: best k in hindsight (test, optimistic)",
                **optimal_fraction(curve)[
                    ["fraction", "contacts", "incremental_responses", "campaign_cost", "profit", "roi"]
                ],
            },
        ]
    )
    plots.plot_profit(
        {n: profit_test[n] for n in [*model_names, "Random targeting"]},
        {"fraction": k_star, "profit": float(at(curve, k_star)["profit"])},
        FIG_DIR / "profit_curve.png",
    )
    gain_lo, gain_hi = bootstrap_profit_gain(y_te, t_te, test_scores[best], econ, k_star, n_boot=n_boot, seed=SEED)
    gain = float(at(curve, k_star)["profit"] - at(curve, 1.0)["profit"])
    summary["profit_gain_vs_everyone"] = {"point": gain, "ci_low": gain_lo, "ci_high": gain_hi}
    sens = []
    for cost in SENSITIVITY_COSTS:
        e = CampaignEconomics(cost_per_contact=cost)
        k = float(optimal_fraction(profit_curve(y_tr, t_tr, oof[best], e))["fraction"])
        c = profit_curve(y_te, t_te, test_scores[best], e)
        sens.append(
            {
                "cost_per_contact": cost,
                "break_even_uplift": e.break_even_uplift,
                "chosen_k": k,
                "profit_targeted": at(c, k)["profit"],
                "profit_everyone": at(c, 1.0)["profit"],
                "gain_vs_everyone": at(c, k)["profit"] - at(c, 1.0)["profit"],
            }
        )
    sens_df = pd.DataFrame(sens)
    summary["economics"] = {
        **asdict(econ),
        "break_even_uplift": econ.break_even_uplift,
        "observed_incremental_spend_per_incremental_visit": spend_ratio,
    }
    summary["business"] = biz.to_dict(orient="records")
    summary["sensitivity"] = sens_df.to_dict(orient="records")
    report += [
        "## Business simulation (test set, scaled to 100,000 customers)\n",
        f"Assumptions: value per incremental visit = ${econ.value_per_response:.2f}, cost per e-mail = "
        f"${econ.cost_per_contact:.2f} -> break-even uplift = {econ.break_even_uplift:.1%}. "
        f"Observed incremental spend per incremental visit = ${spend_ratio:.2f}.\n",
        _md(biz, ".3f"),
        "",
        f"Profit gain of targeted vs blanket campaign: ${gain:,.0f} per 100k customers "
        f"(95% bootstrap CI ${gain_lo:,.0f} to ${gain_hi:,.0f}).\n",
        "### Sensitivity to the cost per e-mail\n",
        _md(sens_df, ".3f"),
        "",
    ]

    # 5. Interpretation ---------------------------------------------------------------
    sub = data.raw.copy()
    sub["recency_bucket"] = pd.cut(sub["recency"], [0, 3, 6, 9, 12], labels=["1-3", "4-6", "7-9", "10-12"])
    sub["recency_bucket"] = sub["recency_bucket"].astype(str)
    seg = pd.concat(
        [
            segment_effects(sub, data.treatment, data.y, v)
            for v in ["womens", "mens", "newbie", "channel", "zip_code", "history_segment", "recency_bucket"]
        ],
        ignore_index=True,
    )
    plots.plot_segments(seg, FIG_DIR / "segment_uplift.png")
    report += [
        "## Model-free uplift by segment (all women's-e-mail vs control rows)\n",
        _md(seg[["variable", "level", "n", "mean_control", "mean_treated", "ate", "ci_low", "ci_high"]]),
        "",
    ]

    tree, text = surrogate_tree(X_te, test_scores[best])
    leaves = tree.apply(X_te)
    rules = leaf_rules(tree, list(X_te.columns))
    leaf_rows = []
    for leaf in np.unique(leaves):
        m = leaves == leaf
        r = ate_with_ci(y_te[m], t_te[m])
        leaf_rows.append(
            {
                "segment_rule": rules[leaf],
                "n_test": int(m.sum()),
                "predicted_uplift": float(test_scores[best][m].mean()),
                "observed_uplift": r["ate"],
                "ci_low": r["ci_low"],
                "ci_high": r["ci_high"],
            }
        )
    leaf_df = pd.DataFrame(leaf_rows).sort_values("predicted_uplift", ascending=False)
    leaf_df["action"] = np.where(
        leaf_df["predicted_uplift"] > econ.break_even_uplift,
        "e-mail",
        np.where(leaf_df["predicted_uplift"] < 0, "do not e-mail (sleeping dogs?)", "do not e-mail (below break-even)"),
    )
    s = test_scores[best]
    top, bottom = s >= np.quantile(s, 0.8), s <= np.quantile(s, 0.2)
    profile = pd.DataFrame(
        {
            "feature": X_te.columns,
            "top_20%_persuadables": X_te[top].mean().to_numpy(),
            "bottom_20%": X_te[bottom].mean().to_numpy(),
            "all_test": X_te.mean().to_numpy(),
        }
    )
    bottom_obs = ate_with_ci(y_te[bottom], t_te[bottom])
    summary["bottom_20_observed_uplift"] = {k: bottom_obs[k] for k in ("ate", "ci_low", "ci_high")}
    summary["share_negative_predicted"] = float((s < 0).mean())
    report += [
        f"## Surrogate segment rules (depth-3 tree on {best} predictions, test set)\n",
        _md(leaf_df),
        "",
        "```",
        text,
        "```",
        "",
        "## Profile: top 20% vs bottom 20% predicted uplift (feature means)\n",
        _md(profile, ".3f"),
        "",
        f"Bottom-20% observed uplift: {bottom_obs['ate']:.4f} "
        f"[{bottom_obs['ci_low']:.4f}, {bottom_obs['ci_high']:.4f}]; share of test customers with "
        f"negative predicted uplift: {(s < 0).mean():.1%}\n",
    ]

    (PROJECT_ROOT / "reports" / "results.md").write_text("\n".join(report), encoding="utf-8")
    (ART_DIR / "summary.json").write_text(json.dumps(summary, indent=2, default=float), encoding="utf-8")
    pd.DataFrame({"treatment": t_te, "y": y_te, **test_scores}).to_csv(ART_DIR / "test_scores.csv", index=False)
    return summary


if __name__ == "__main__":
    out = run()
    print(json.dumps({k: out[k] for k in ("best_model_by_cv", "business")}, indent=2, default=float))
