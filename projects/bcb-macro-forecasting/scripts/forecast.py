"""Live 12-month forecast of the household default rate with calibrated intervals.

Point forecast: equal-weight ensemble of AutoETS and LightGBM+exog (best backtest MAE).
Intervals: per-horizon conformal half-widths from all backtest errors of the ensemble
(requires artifacts/backtest_conformal.csv from scripts/run_backtest.py).
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")  # headless: figures are only saved to disk
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from bcb_forecast import plots
from bcb_forecast.backtest import final_conformal_bands
from bcb_forecast.data import PROJECT_ROOT, TARGET
from bcb_forecast.features import DEFAULT_EXOG
from bcb_forecast.models import forecast_lgbm, forecast_stats

ART = PROJECT_ROOT / "artifacts"
REP = PROJECT_ROOT / "reports"
H = 12


def main() -> None:
    panel = pd.read_csv(PROJECT_ROOT / "data" / "panel.csv", index_col=0, parse_dates=True).asfreq("MS")
    y = panel[TARGET].dropna()
    ets = forecast_stats(y, H, models=("AutoETS",))
    lgbm = forecast_lgbm(panel, H, exog=DEFAULT_EXOG)
    fc = pd.DataFrame({"ds": ets["ds"], "horizon": ets["horizon"],
                       "AutoETS": ets["mean"].to_numpy(), "LightGBM+exog": lgbm["mean"].to_numpy()})
    fc["mean"] = fc[["AutoETS", "LightGBM+exog"]].mean(axis=1)

    bt = pd.read_csv(ART / "backtest_conformal.csv", parse_dates=["ds", "cutoff"])
    bands = final_conformal_bands(bt, "Ensemble")
    fc = fc.merge(bands, on="horizon")
    for lv in (80, 95):
        fc[f"lo_{lv}"] = fc["mean"] - fc[f"q_{lv}"]
        fc[f"hi_{lv}"] = fc["mean"] + fc[f"q_{lv}"]
    fc = fc.drop(columns=["q_80", "q_95"])
    fc.to_csv(ART / "final_forecast.csv", index=False)

    tbl = fc.assign(month=pd.to_datetime(fc["ds"]).dt.strftime("%Y-%m")).set_index("month")
    tbl = tbl[["mean", "lo_80", "hi_80", "lo_95", "hi_95", "AutoETS", "LightGBM+exog"]].round(2)
    md = [
        "# Final forecast (generated by scripts/forecast.py)\n",
        f"Household credit default rate (SGS 21084, % of portfolio 90+ days past due). "
        f"Last observed: {y.index[-1]:%Y-%m} = {y.iloc[-1]:.2f}%.\n",
        tbl.to_markdown(), "\n",
    ]
    (REP / "final_forecast.md").write_text("\n".join(md), encoding="utf-8")
    print(tbl.to_string())

    plots.style()
    fig, ax = plt.subplots(figsize=(10, 4.6))
    plots.fan_chart(y, fc, f"Household default rate: 12-month forecast from {y.index[-1]:%b %Y}",
                    ax=ax, color=plots.MODEL_COLORS["Ensemble"], history_months=96)
    ax.text(0.99, 0.02, "Ensemble of AutoETS + LightGBM (macro drivers); intervals calibrated "
            "on 2017-2026 backtest errors.\nSource: Banco Central do Brasil, SGS series 21084.",
            transform=ax.transAxes, ha="right", va="bottom", fontsize=8, color=plots.INK_2)
    fig.tight_layout()
    fig.savefig(REP / "figures" / "final_forecast.png", dpi=110)
    print("wrote", REP / "figures" / "final_forecast.png")


if __name__ == "__main__":
    main()
