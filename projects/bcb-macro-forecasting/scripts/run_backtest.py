"""Rolling-origin backtest of all models; writes artifacts/backtest.csv, a metrics summary
(reports/backtest_summary.md) and figures in reports/figures/."""

from __future__ import annotations

import argparse
import time

import matplotlib

matplotlib.use("Agg")  # headless: figures are only saved to disk
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from bcb_forecast import plots
from bcb_forecast.backtest import (
    add_ensemble,
    conformalize,
    make_cutoffs,
    rolling_origin,
    skill_vs,
    summarize,
)
from bcb_forecast.data import PROJECT_ROOT
from bcb_forecast.models import forecast_all

ART = PROJECT_ROOT / "artifacts"
REP = PROJECT_ROOT / "reports"
FIG = REP / "figures"
ENSEMBLE_MEMBERS = ["AutoETS", "LightGBM+exog"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--first-cutoff", default="2017-01-01")
    parser.add_argument("--step", type=int, default=3, help="months between cutoffs")
    parser.add_argument("--horizon", type=int, default=12)
    parser.add_argument("--reuse", action="store_true",
                        help="reuse artifacts/backtest.csv instead of re-running the models")
    args = parser.parse_args()

    panel = pd.read_csv(PROJECT_ROOT / "data" / "panel.csv", index_col=0, parse_dates=True).asfreq("MS")
    cutoffs = make_cutoffs(panel.index, args.first_cutoff, args.horizon, args.step)
    print(f"{len(cutoffs)} cutoffs: {cutoffs[0]:%Y-%m} .. {cutoffs[-1]:%Y-%m}")
    ART.mkdir(exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    if args.reuse and (ART / "backtest.csv").exists():
        bt = pd.read_csv(ART / "backtest.csv", parse_dates=["ds", "cutoff"])
    else:
        t0 = time.time()
        bt = rolling_origin(panel, lambda p: forecast_all(p, args.horizon), cutoffs, args.horizon)
        print(f"backtest done in {time.time() - t0:.0f}s")
        bt.to_csv(ART / "backtest.csv", index=False)

    bt = add_ensemble(bt, ENSEMBLE_MEMBERS, "Ensemble")
    bt_conf = conformalize(bt)
    bt_conf.to_csv(ART / "backtest_conformal.csv", index=False)

    overall = summarize(bt)
    overall["MAE_skill_vs_naive"] = skill_vs(overall, "Naive")
    overall = overall.sort_values("MASE")
    per_h = summarize(bt, ["model", "horizon"])
    conf = summarize(bt_conf).loc[overall.index]
    conf_h = summarize(bt_conf, ["model", "horizon"])
    # Compare native vs. conformal on the *same* forecasts (those past the conformal warm-up).
    keys = ["model", "cutoff", "horizon"]
    same_rows = bt.merge(bt_conf.loc[bt_conf["lo_80"].notna(), keys], on=keys)
    native = summarize(same_rows).reindex(overall.index)
    pre_surge = summarize(bt_conf[pd.to_datetime(bt_conf["ds"]) < "2025-01-01"]).loc[overall.index]
    cov_cmp = pd.DataFrame({
        "native_cov80": native["coverage_80"], "native_cov95": native["coverage_95"],
        "native_width80": native["width_80"],
        "conformal_cov80": conf["coverage_80"], "conformal_cov95": conf["coverage_95"],
        "conformal_width80": conf["width_80"], "n": conf["n_intervals"],
        "conformal_cov80_pre2025": pre_surge["coverage_80"],
        "conformal_cov95_pre2025": pre_surge["coverage_95"],
    })
    print(cov_cmp.round(3).to_string())
    no_covid = summarize(bt[~pd.to_datetime(bt["ds"]).dt.year.isin([2020, 2021])])
    point_cols = ["MAE", "RMSE", "MAPE", "MASE", "bias", "n", "MAE_skill_vs_naive"]
    print(overall[point_cols].round(3).to_string())

    mae_tbl = per_h["MAE"].unstack("horizon")[[1, 3, 6, 12]].loc[overall.index]
    mae_tbl.columns = [f"h={c}" for c in mae_tbl.columns]
    cov_tbl = conf_h["coverage_80"].unstack("horizon")[[1, 3, 6, 12]].loc[overall.index]
    cov_tbl.columns = [f"h={c}" for c in cov_tbl.columns]
    md = [
        "# Backtest summary (generated by scripts/run_backtest.py)\n",
        f"Expanding-window rolling origin, {len(cutoffs)} cutoffs every {args.step} months "
        f"({cutoffs[0]:%Y-%m} to {cutoffs[-1]:%Y-%m}), horizons 1-{args.horizon}, "
        f"{len(bt) // bt['model'].nunique()} forecasts per model.\n",
        "## Point accuracy (all horizons pooled)\n", overall[point_cols].round(3).to_markdown(), "\n",
        "## MAE (percentage points) by horizon\n", mae_tbl.round(3).to_markdown(), "\n",
        "## Interval calibration: native vs. online conformal intervals\n",
        "Native = model-implied bands (statsforecast analytic; LightGBM quantile regression). "
        "Conformal = mean +/- empirical quantile of the same model's past absolute errors at the "
        "same horizon, using only errors observable at the cutoff (first 8 per horizon = warm-up). "
        "Both evaluated on the same forecasts (past the warm-up). The Ensemble has no native "
        "intervals. `*_pre2025` = conformal coverage for target months before 2025, i.e. before "
        "the 2025-26 default surge.\n",
        cov_cmp.round(3).to_markdown(), "\n",
        "## Coverage of the nominal 80% conformal interval by horizon\n",
        cov_tbl.round(2).to_markdown(), "\n",
        "## Point accuracy excluding target months in 2020-2021 (pandemic)\n",
        no_covid.sort_values("MASE")[point_cols[:-1]].round(3).to_markdown(), "\n",
    ]
    (REP / "backtest_summary.md").write_text("\n".join(md), encoding="utf-8")

    plots.style()
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.2))
    plots.metric_by_horizon(per_h, "MAE", "Backtest MAE by horizon (p.p., lower is better)", axes[0])
    plots.metric_by_horizon(conf_h, "coverage_80", "Coverage of 80% conformal intervals", axes[1])
    axes[1].axhline(0.8, color=plots.INK_2, lw=1, ls=":")
    axes[1].set_ylim(0, 1.05)
    axes[1].get_legend().remove()
    fig.tight_layout()
    fig.savefig(FIG / "backtest_by_horizon.png", dpi=110)
    print("wrote", FIG / "backtest_by_horizon.png")


if __name__ == "__main__":
    main()
